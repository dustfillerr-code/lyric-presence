export function karmaBadge(k: number) {
  if (k >= 50) return "💎 Легенда";
  if (k >= 20) return "👑 Элита";
  if (k >= 5) return "🌟 Уважаемый";
  if (k >= 0) return "✨ Новичок";
  return "⚠️ Сомнительный";
}

